export function Progress({
  value,
  className,
  label = "Progreso",
}: {
  value: number | null;
  className?: string;
  label?: string;
}) {
  const determinate = value !== null;
  const safe = determinate ? Math.max(0, Math.min(100, value)) : 0;
  return (
    <div
      className={cn("h-2 w-full overflow-hidden rounded-full bg-muted", className)}
      role="progressbar"
      aria-label={label}
      aria-valuemin={0}
      aria-valuemax={100}
      aria-valuenow={determinate ? Math.round(safe) : undefined}
    >
      <div
        className={cn(
          "h-full rounded-full bg-primary transition-[width] duration-300",
          !determinate && "w-1/3 animate-pulse",
        )}
        style={determinate ? { width: `${safe}%` } : undefined}
      />
    </div>
  );
}

